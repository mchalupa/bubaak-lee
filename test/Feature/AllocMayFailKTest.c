// The replay of a .ktest follows the choices
// RUN: rm -rf %t.klee-replay-01
// RUN: %klee --output-dir=%t.klee-replay-01 -alloc-may-fail --replay-ktest-file=%t.klee-gen-01/test000001.ktest %t.bc > %t.outr 2>&1
// RUN: FileCheck --check-prefix=SECOND %s < %t.outr

#include "klee/klee.h"

#include <stdio.h>
#include <stdlib.h>

static void choices(char first, char second) {
  char a, b;
  klee_make_symbolic(&a, sizeof(a), "__bbk_alloc_fail");
  klee_make_symbolic(&b, sizeof(b), "__bbk_alloc_fail");
  klee_assume(a == first);
  klee_assume(b == second);
}

void SeedSecondFails(void) { choices(0, 1); }
void SeedFirstFails(void) { choices(1, 0); }

int main(void) {
  char *p = malloc(4);
  char *q = malloc(4);
  if (p == NULL && q == NULL)
    printf("both failed\n");
  else if (p == NULL)
    printf("first failed\n");
  else if (q == NULL)
    printf("second failed\n");
  else
    printf("none failed\n");
  free(p);
  free(q);
  return 0;
}

